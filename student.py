# ---------- Section 3: Interactive mode vs Script mode ----------
print("\n=== Interactive Mode vs Script Mode ===")
print("Interactive mode:")
print("  - You type one command at a time at the >>> prompt.")
print("  - Python runs each line immediately and shows the result.")
print("  - Code is not saved. Good for quick tests and learning.")
print("Script mode:")
print("  - You write many lines in a .py file and run them together.")
print("  - The code is saved and can be run again and again.")
print("  - Good for bigger programs.")

# ---------- Section 4: Best mode for a student management application ----------
print("\n=== Best Mode for a Student Management Application ===")
print("Script mode is more appropriate.")
print("Reason: a complete application has many lines of code that must be")
print("saved, edited, tested and reused. Interactive mode forgets the code")
print("once you close it.")
