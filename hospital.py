# hospital.py
# Task 1: Hospital Patient System

# ---------- Section 1: Store patient details in variables ----------
patient_name = "John Kamau"   # string
patient_id = "P001"           # string
patient_age = 35              # integer
patient_gender = "Male"       # string

# ---------- Section 2: Display details using print() ----------
print("--- Patient Details (using print) ---")
print("Patient Name:", patient_name)
print("Patient ID:", patient_id)
print("Age:", patient_age)
print("Gender:", patient_gender)

# ---------- Section 3: Display details using an f-string ----------
print("\n--- Patient Details (using f-string) ---")
print(f"Patient Name: {patient_name}")
print(f"Patient ID: {patient_id}")
print(f"Age: {patient_age}")
print(f"Gender: {patient_gender}")
